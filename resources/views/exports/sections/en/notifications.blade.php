Notifications you received in the Dashboard.

You can find the content of each in your dashboard as these may contain more complex stuff than a simple message.

| Field | Type | Description |
|---|---|---|
| `id` | string | Notification ID in UUID format |
| `type` | string | Notification Class |
| `read_at` | datetime, nullable | the time when you have marked the notification as "read" |
| `created_at` | datetime | When it was sent to you |
| `updated_at` | datetime | When the notification was updated |
